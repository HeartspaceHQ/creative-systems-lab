import { useState } from "react";
import { CheckList } from "../../components/CheckList";
import { ColourTable, Provenance } from "../../components/Provenance";
import { checkLabel, dateTime } from "../../format";
import { studioApi } from "../../studio/api";
import { useWorkspace } from "../../workspace/context";
import type { Verdict } from "../../types";
import type { LibraryItem } from "./items";
import { ReviewForm } from "./ReviewForm";

interface Decided {
  readonly verdict: "approve" | "reject";
  readonly by: string;
  readonly at: string;
  readonly note: string;
}

function decidedOf(item: LibraryItem): Decided | null {
  if (item.asset?.decision != null) {
    const d = item.asset.decision;
    return { verdict: d.verdict, by: d.reviewer, at: d.decidedAt, note: d.note };
  }
  const d = item.origin?.candidate.decision;
  return d == null ? null : { verdict: d.verdict, by: d.reviewer, at: d.decidedAt, note: d.note };
}

function checkSummary(item: LibraryItem): string | null {
  const candidate = item.origin?.candidate;
  if (candidate === undefined) return null;
  const failed = candidate.checks.filter((c) => !c.passed && c.hard).map((c) => checkLabel(c.name).toLowerCase());
  if (failed.length === 0) return "Passed the automatic colour checks.";
  return `The automatic checks flagged this image: ${failed.join(", ")}. Look at it yourself before approving.`;
}

/** Who approved it, when, and where it came from: quiet, but always there. */
function Traceability({ item }: { item: LibraryItem }) {
  const decided = decidedOf(item);
  const { asset, origin } = item;
  return (
    <dl className="facts trace">
      <dt>Source</dt>
      <dd>
        {asset?.origin === "imported"
          ? `Imported from ${asset.source.fileName ?? "a file"}`
          : item.title.replace("Made by", "Generated by")}
        {origin !== null && <span className="fine"> {dateTime(origin.candidate.createdAt)}</span>}
      </dd>
      <dt>Size</dt>
      <dd className="num">
        {String(item.width)} × {String(item.height)} px
      </dd>
      {decided !== null && (
        <>
          <dt>{decided.verdict === "approve" ? "Approved" : "Rejected"}</dt>
          <dd>
            by {decided.by}
            <span className="fine"> {dateTime(decided.at)}</span>
            {decided.note !== "" && <span className="fine quote-note">“{decided.note}”</span>}
          </dd>
        </>
      )}
      {asset?.decision?.rightsConfirmed === true && (
        <>
          <dt>Rights</dt>
          <dd>Confirmed by {asset.decision.reviewer}</dd>
        </>
      )}
    </dl>
  );
}

function TechnicalDetails({ item }: { item: LibraryItem }) {
  const { origin, asset } = item;
  return (
    <details className="technical">
      <summary>Technical details</summary>
      {asset !== null && (
        <dl className="facts">
          {asset.source.licence !== null && (
            <>
              <dt>Licence</dt>
              <dd>{asset.source.licence}</dd>
            </>
          )}
          <dt>Image hash</dt>
          <dd className="hash">{asset.sha256}</dd>
        </dl>
      )}
      {origin !== null && (
        <>
          <Provenance candidate={origin.candidate} />
          <CheckList checks={origin.candidate.checks} warnings={origin.candidate.warnings} kind={origin.run.kind} />
          <ColourTable candidate={origin.candidate} palette={origin.run.palette} />
        </>
      )}
    </details>
  );
}

function UseInDesign({ item, onUse }: { item: LibraryItem; onUse: (assetId: string) => void }) {
  const { project, design, refresh, placeInDesign } = useWorkspace();
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const inUse = item.asset !== null && design.draft?.asset === item.asset.id;

  const use = (): void => {
    setBusy(true);
    setError(null);
    const ready = async (): Promise<string> => {
      if (item.asset !== null) return item.asset.id;
      if (item.origin === null) throw new Error("This image has no record to use.");
      const created = await studioApi.assetFromRun(project.id, item.origin.run.id, item.origin.candidate.id);
      await refresh();
      return created.id;
    };
    ready()
      .then(async (id) => {
        onUse(id);
        await placeInDesign(id);
      })
      .catch((failure: unknown) => {
        setError(failure instanceof Error ? failure.message : "Could not use this image.");
      })
      .finally(() => {
        setBusy(false);
      });
  };

  return (
    <div className="use-in-design">
      <button type="button" className="primary" disabled={busy} onClick={use}>
        {inUse ? "Open in design" : "Use in design"}
      </button>
      {inUse && <p className="fine">This image is in your design now.</p>}
      {error !== null && (
        <p role="alert" className="error">
          {error}
        </p>
      )}
    </div>
  );
}

const STATE_TEXT = { review: "Needs your decision", approved: "Approved", rejected: "Rejected" } as const;

export function Inspector(props: { item: LibraryItem; onDecided: (nextKey: string, verdict: Verdict) => void }) {
  const { item, onDecided } = props;
  const [changing, setChanging] = useState(false);
  const summary = checkSummary(item);
  return (
    <aside className="inspector" aria-label="Review this image">
      <div className="inspector-status">
        <h2>{item.title}</h2>
        <span className={`status status-${item.state === "review" ? "pending" : item.state}`}>
          <span className="status-dot" aria-hidden="true" />
          {STATE_TEXT[item.state]}
        </span>
      </div>
      {item.state === "approved" && <UseInDesign item={item} onUse={() => undefined} />}
      {summary !== null && <p className={item.flagged ? "note" : "fine"}>{summary}</p>}
      {item.state === "review" || changing ? (
        <section className="decision" aria-label="Your decision">
          <h3>{item.state === "review" ? "Your decision" : "Change the decision"}</h3>
          <ReviewForm
            key={item.key}
            item={item}
            onDecided={(key, verdict) => {
              setChanging(false);
              onDecided(key, verdict);
            }}
          />
        </section>
      ) : (
        <button
          type="button"
          className="link-button"
          onClick={() => {
            setChanging(true);
          }}
        >
          Change the decision
        </button>
      )}
      <Traceability item={item} />
      <TechnicalDetails item={item} />
    </aside>
  );
}
